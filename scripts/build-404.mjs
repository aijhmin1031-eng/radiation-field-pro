/** public/404.html 을 만든다 — 공통 셸 v3 머리글 + renderNotFound + 꼬리말 (2026-10-28, T3). `npm run build` 가 먼저 돈다.
 *
 *  ★ 왜 public/ 에 두나: Vite 가 public/ 을 dist/ 에 그대로 복사하고, Vercel 은 산출물 뿌리의 404.html 을 HTTP 404 응답에
 *    자동으로 쓴다(그전에는 text/plain "NOT_FOUND" 78 바이트 — 링크 0, 홈으로 갈 길이 없었다). Cloudflare Workers 로
 *    옮길 때도 `not_found_handling: "404-page"` 가 같은 파일을 쓴다(설계안 §3.5).
 *  ★ 커밋한다 — dev 서버(`vite`)도 public/ 을 그대로 내주므로 /404.html 을 바로 볼 수 있다. 사본(shell/)이 바뀌면 빌드가
 *    다시 만들고, gate/check-shell 이 public · dist 둘 다 render.mjs 출력과 바이트 동일한지 잰다. 손으로 고치지 않는다. */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT, SECTION, loadShell, fragmentsFor } from "./shell-page.mjs";

export async function render404() {
  const shell = await loadShell();
  const { spec, R } = shell;
  const f = fragmentsFor(shell, "notFound");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta name="theme-color" content="#e8eae6" media="(prefers-color-scheme: light)" />
<meta name="theme-color" content="#121517" media="(prefers-color-scheme: dark)" />
<title>Page not found · Field Pro · Radiation Lab</title>
<meta name="description" content="This address has no page. The Field Pro workbench and the rest of Radiation Lab are linked here." />
<meta name="robots" content="noindex, follow" />
<link rel="icon" href="/favicon.svg" type="image/svg+xml" />
<!-- rl-shell v${spec.version} — generated by scripts/build-404.mjs from shell/shell.json. Do not edit by hand; run npm run build:404. -->
${f.head}
<style>
  * { box-sizing: border-box; }
  html, body { margin: 0; background: rgb(var(--c-paper)); color: rgb(var(--c-ink)); font-family: var(--body); font-size: 15px; line-height: 1.7; }
  body { word-break: keep-all; overflow-wrap: break-word; }
  a { color: rgb(var(--c-accent)); }
</style>
</head>
<body>
<a class="skip" href="#main">Skip to main content</a>
${f.header}
${R.renderNotFound(spec, { section: SECTION })}
${f.footer}
</body>
</html>
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = join(ROOT, "public", "404.html");
  const html = await render404();
  const same = existsSync(out) && readFileSync(out, "utf8") === html;
  if (!same) writeFileSync(out, html);
  console.log(`${same ? "＝ " : "✏️ "} public/404.html ${html.length}자 — 공통 셸 v${JSON.parse(readFileSync(join(ROOT, "shell/shell.json"), "utf8")).version}`);
}
